# Безопасное чтение - решение
#
# Задача: Попробовать открыть 'data.txt'. Если файла нет — записать 'ERROR' в 'log.txt'.
# Если файл есть — скопировать его содержимое в 'log.txt'.
#
# Алгоритм решения:
# 1. Используем конструкцию try/except для обработки возможных ошибок
# 2. Пытаемся открыть и прочитать data.txt
# 3. Если успешно — записываем содержимое в log.txt
# 4. Если возникает FileNotFoundError — записываем 'ERROR' в log.txt
#
# Почему используем try/except:
# - Это стандартный подход Python для обработки исключительных ситуаций
# - Позволяет программе продолжиться даже при ошибке
# - Избегает необходимости проверять существование файла заранее

try:
    # Пытаемся открыть файл для чтения
    # Если файл не существует, Python выбросит FileNotFoundError
    with open('data.txt', 'r') as f:
        content = f.read()
    
    # Если файл успешно прочитан, записываем содержимое в log.txt
    with open('log.txt', 'w') as f:
        f.write(content)

except FileNotFoundError:
    # Этот блок выполнится только если файл data.txt не найден
    # Записываем сообщение об ошибке в log.txt
    with open('log.txt', 'w') as f:
        f.write('ERROR')

# Бинарная проверка - решение
#
# Задача: Проверить первые 4 байта файла 'file.bin'.
# Если это 0x89 0x50 0x4E 0x47 - записать 'PNG' в 'type.txt', иначе 'UNKNOWN'.
#
# Алгоритм решения:
# 1. Открываем файл в бинарном режиме ('rb')
# 2. Читаем первые 4 байта
# 3. Сравниваем с сигнатурой PNG
# 4. Записываем результат в type.txt
#
# Сигнатура PNG (89 50 4E 47 в шестнадцатеричном формате):
# Это "магические числа" формата PNG, которые идентифицируют тип файла.
# В ASCII это выглядит как: ‹P›G (где первый символ непечатаемый)
#
# Почему используем бинарный режим:
# - Текстовый режим может исказить байты (кодировки, переводы строк)
# - Бинарный режим читает данные "как есть"

# Открываем файл в бинарном режиме ('rb' = read binary)
with open('file.bin', 'rb') as f:
    # Читаем первые 4 байта
    # read(4) возвращает объект bytes длиной 4 байта
    header = f.read(4)

# Сравниваем с сигнатурой PNG
# b'\x89\x50\x4E\x47' - это байтовая строка (bytes literal)
# \x означает шестнадцатеричное значение байта
if header == b'\x89\x50\x4E\x47':
    result = 'PNG'
else:
    result = 'UNKNOWN'

# Записываем результат в текстовый файл
with open('type.txt', 'w') as f:
    f.write(result)

# Поиск файлов - решение
#
# Задача: Создать список всех .txt файлов в папке 'project' (включая подпапки)
# и записать их имена в 'found.txt'.
#
# Алгоритм решения:
# 1. Используем os.walk() для рекурсивного обхода директории
# 2. Для каждого файла проверяем расширение (.txt)
# 3. Сохраняем имена подходящих файлов в список
# 4. Записываем список в found.txt
#
# Структура папки project:
#   project/
#   ├── a.txt        <- нужен
#   └── sub/
#       ├── b.txt    <- нужен
#       └── c.py     <- не нужен
#
# Ожидаемый результат: a.txt, b.txt

import os

# Создаём пустой список для хранения имён файлов
txt_files = []

# os.walk() генерирует имена файлов в дереве каталогов
# Для каждого каталога возвращает кортеж (root, dirs, files):

# Пример создания кортежа
# point = (10, 20)
# colors = ('red', 'green', 'blue')
# Обращение по индексу
# print(point[0])  # 10
# print(colors[1])  # 'green'
# Распаковка кортежа
# x, y = point  # x=10, y=20


# - root  - путь к текущей директории
# - dirs  - список поддиректорий
# - files - список файлов в текущей директории
for root, dirs, files in os.walk('project'):
    for file in files:
        # Проверяем, заканчивается ли имя файла на '.txt'
        if file.endswith('.txt'):
            txt_files.append(file)

# Записываем результаты в файл
# join() соединяет элементы списка через разделитель (новая строка)
with open('found.txt', 'w') as f:
    f.write('\n'.join(txt_files))

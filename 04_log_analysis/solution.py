# Анализатор логов - решение
#
# Задача: В файле 'server.log' найти все строки с ошибкой '404'.
# Записать их количество в 'stats.txt'.
#
# Алгоритм решения:
# 1. Открываем server.log для чтения
# 2. Проходим по каждой строке файла
# 3. Проверяем, содержит ли строка '404'
# 4. Считаем количество совпадений
# 5. Записываем итоговое число в stats.txt
#
# Пример содержимого server.log:
#   200 OK
#   404 Not Found      <- совпадение
#   500 Error
#   404 Not Found      <- совпадение
#
# Ожидаемый результат: 2

# Инициализируем счётчик
count = 0

# Открываем файл логов и читаем построчно
# Построчное чтение эффективно для больших файлов
with open('server.log', 'r') as f:
    for line in f:
        # Проверяем, содержит ли строка '404'
        # Оператор 'in' возвращает True если подстрока найдена
        if '404' in line:
            count += 1  # Увеличиваем счётчик

# Записываем результат в файл
# Преобразуем число в строку с помощью str()
with open('stats.txt', 'w') as f:
    f.write(str(count))

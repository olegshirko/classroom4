# Патч конфигурации - решение
#
# Задача: В файле 'config.env' найти строку 'DEBUG=False' и заменить её на 'DEBUG=True'.
# Остальные строки не менять.
#
# Алгоритм решения:
# 1. Читаем все строки из config.env в список
# 2. Открываем тот же файл для записи
# 3. Проходим по каждой строке:
#    - Если строка равна 'DEBUG=False' - заменяем на 'DEBUG=True'
#    - Иначе - записываем без изменений
#
# Пример содержимого config.env:
#   VERSION=1.0
#   DEBUG=False    <- нужно заменить
#   PORT=8080
#
# Ожидаемый результат:
#   VERSION=1.0
#   DEBUG=True
#   PORT=8080

# Читаем все строки из файла
# readlines() возвращает список строк с символами новой строки
with open('config.env', 'r') as f:
    lines = f.readlines()

# Записываем изменённые строки обратно в файл
with open('config.env', 'w') as f:
    for line in lines:
        # Проверяем точное совпадение строки (с учётом strip() для удаления \n)
        # Используем strip() чтобы сравнивать только содержимое, без символа новой строки
        if line.strip() == 'DEBUG=False':
            # Заменяем на DEBUG=True с символом новой строки
            f.write('DEBUG=True\n')
        else:
            # Записываем строку без изменений
            f.write(line)
